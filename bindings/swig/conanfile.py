import os

from conan import ConanFile
from conan.tools.cmake import CMake, CMakeDeps, CMakeToolchain, cmake_layout


class LibcosimCConan(ConanFile):
    """
    The libcosim bindings.

    As a package (`conan create`), this is the C library `libcosim-c`: the C
    API generated by SWIG's C backend (library + `cosim_c.h`), built against
    the libcosim Conan package.

    As a consumer (`conan install`), it provides libcosim, SWIG and, with
    `-o "&:java=True"`, a JDK for building the other packages (Python wheel,
    Java JAR, NuGet package, Julia package); see packaging/README.md.

    The libcosim package to build against is given by the environment
    variable LIBCOSIM_REF (default below). Released bindings would require a
    released libcosim, e.g. "libcosim/[>=0.12 <0.13]@osp/stable".
    """

    name = "libcosim-c"
    version = "0.11.3"  # follows the libcosim version
    license = "MPL-2.0"
    url = "https://github.com/open-simulation-platform/libcosim"
    description = "C API for libcosim, generated with SWIG"
    package_type = "shared-library"
    settings = "os", "compiler", "build_type", "arch"
    options = {"java": [True, False]}
    default_options = {"java": False}

    exports_sources = (
        "CMakeLists.txt", "cosim.i", "cmake/*", "c/*",
        "python/*", "java/*", "csharp/*", "julia/*",
    )

    def requirements(self):
        # transitive_headers: libcosim's package ships its own CMake config,
        # which needs the CMake configs of all of libcosim's dependencies
        # (including header-only ones such as Microsoft.GSL); Conan only
        # generates those for consumers that see libcosim's headers.
        self.requires(os.environ.get("LIBCOSIM_REF", "libcosim/0.11.3@spike/testing"),
                      transitive_headers=True)

    def build_requirements(self):
        self.tool_requires("swig/4.4.1")  # pinned: the C backend is experimental
        if self.options.java:
            self.tool_requires("zulu-openjdk/21.0.11")

    def layout(self):
        cmake_layout(self)

    def generate(self):
        tc = CMakeToolchain(self)
        # Only the C library is built when packaging; the other languages are
        # enabled by their own packaging builds.
        tc.cache_variables["LIBCOSIM_SWIG_C"] = True
        tc.cache_variables["LIBCOSIM_SWIG_JULIA"] = False
        tc.cache_variables["LIBCOSIM_SWIG_PYTHON"] = False
        tc.cache_variables["LIBCOSIM_SWIG_JAVA"] = False
        tc.cache_variables["LIBCOSIM_SWIG_CSHARP"] = False
        tc.cache_variables["LIBCOSIM_SWIG_INSTALL"] = True
        tc.generate()
        CMakeDeps(self).generate()

    def build(self):
        cmake = CMake(self)
        cmake.configure()
        cmake.build(target="cosim_c")

    def package(self):
        cmake = CMake(self)
        cmake.install(component="c")

    def package_info(self):
        self.cpp_info.libs = ["cosim_c"]
        self.cpp_info.set_property("cmake_file_name", "libcosim-c")
        self.cpp_info.set_property("cmake_target_name", "libcosim-c::cosim_c")
