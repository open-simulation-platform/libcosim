"""
Generates the Julia `ccall` layer of the Libcosim package from the C header
produced by SWIG's C backend (cosim_c_wrap.h).

Usage: python generate_julia.py <cosim_c_wrap.h> <generated.jl>

For each C function `SWIGIMPORT <ret> <name>(<params>);` it emits a Julia
function of the same name that
  - calls it with `ccall` on `libcosim_c`,
  - raises a Julia `CosimError` if the call left a pending libcosim error,
  - returns objects (`cosim_<type>*`) as `Handle`s that call the matching
    `cosim_<type>_delete` when garbage-collected (all returned objects are
    caller-owned, see the header),
  - returns strings as Julia `String`s, releasing the C copy with
    `cosim_free_string`.
Enumerators become `const` values.
"""
import re
import sys

# C type -> Julia type for ccall
SCALARS = {
    "void": "Cvoid",
    "bool": "Bool",
    "int": "Cint",
    "unsigned int": "Cuint",
    "long": "Clong",
    "long long": "Clonglong",
    "unsigned long": "Culong",
    "int64_t": "Int64",
    "uint64_t": "UInt64",
    "size_t": "Csize_t",
    "double": "Cdouble",
    "float": "Cfloat",
    "char": "Cchar",
}

# Functions that manage the error state themselves (no automatic check), and
# functions whose results must not be wrapped (borrowed or special).
NO_CHECK = re.compile(r"^cosim_(last_error_code|last_error_message|clear_last_error|free_string|SWIG_CException_.*)$")
NO_OWN = re.compile(r"^cosim_SWIG_CException_")
BORROWED_STRINGS = {"cosim_SWIG_CException_msg_get"}


def parse_type(ctype):
    """Returns (kind, julia_type, c_class) for a C type."""
    t = " ".join(ctype.replace("*", " * ").split())
    if t in ("const char *", "char *"):
        return "string", "Ptr{Cchar}", None
    if t.startswith("enum "):
        return "enum", "Cint", None
    if t.endswith("*"):
        base = t[:-1].strip().replace("const ", "")
        return "object", "Ptr{Cvoid}", base
    if t in SCALARS:
        return "scalar", SCALARS[t], None
    raise ValueError(f"unsupported C type: {ctype!r}")


def parse_params(params):
    params = params.strip()
    if params in ("", "void"):
        return []
    result = []
    for p in params.split(","):
        p = p.strip()
        m = re.match(r"^(.*?)([A-Za-z_][A-Za-z0-9_]*)$", p)
        ctype, name = m.group(1).strip(), m.group(2)
        result.append((ctype, name))
    return result


def main(header_path, output_path):
    text = open(header_path, encoding="utf-8").read()
    functions = re.findall(r"^SWIGIMPORT\s+(.+?)\s*\b(cosim_[A-Za-z0-9_]+)\s*\((.*?)\);", text, re.M)
    names = {name for _, name, _ in functions}
    enums = re.findall(r"^enum\s+(cosim_[A-Za-z0-9_]+)\s*\{(.*?)\};", text, re.M | re.S)

    out = [
        "# Generated by generate_julia.py from the libcosim C header. Do not edit.",
        "",
    ]

    for enum_name, body in enums:
        out.append(f"# enum {enum_name}")
        value = -1
        for item in body.split(","):
            item = item.strip()
            if not item:
                continue
            if "=" in item:
                key, val = [x.strip() for x in item.split("=", 1)]
                value = int(val, 0)
            else:
                key = item
                value += 1
            out.append(f"const {key} = Cint({value})")
        out.append("")

    for ret, name, params in functions:
        kind, jret, cls = parse_type(ret)
        ps = parse_params(params)
        jargs = [f"a{i}" for i in range(len(ps))]
        # String parameters as Cstring (checked for embedded NULs), returned
        # strings as Ptr{Cchar} (they must be freed).
        jtypes = ["Cstring" if parse_type(t)[0] == "string" else parse_type(t)[1] for t, _ in ps]
        argtuple = "(" + ", ".join(jtypes) + ("," if len(jtypes) == 1 else "") + ")"
        call = f"ccall((:{name}, libcosim_c), {jret}, {argtuple}{''.join(', ' + a for a in jargs)})"
        check = "" if NO_CHECK.match(name) else "\n    check_error()"
        sig = f"function {name}({', '.join(jargs)})"
        if kind == "string":
            free = "false" if name in BORROWED_STRINGS else "true"
            body = f"    r = {call}{check}\n    return take_string(r, {free})"
        elif kind == "object" and not NO_OWN.match(name):
            deleter = f"{cls}_delete"
            if deleter in names and name != deleter:
                body = f"    r = {call}{check}\n    return own(r, :{deleter})"
            else:
                body = f"    r = {call}{check}\n    return r"
        elif kind == "scalar" and jret == "Cvoid":
            body = f"    {call}{check}\n    return nothing"
        else:
            body = f"    r = {call}{check}\n    return r"
        out.append(f"{sig}\n{body}\nend\n")

    with open(output_path, "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    print(f"generated {len(functions)} functions and {len(enums)} enums -> {output_path}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
