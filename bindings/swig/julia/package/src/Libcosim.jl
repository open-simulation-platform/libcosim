"""
Julia interface to libcosim, on its C API (generated by SWIG's C backend).

All functions of the C API are available under their C names
(`cosim_execution_step`, ...); see `generated.jl`. Compared to calling the C
library directly:
  - objects returned by the API are `Handle`s, released automatically by the
    garbage collector (every returned object is caller-owned);
  - a libcosim error raises a `CosimError` carrying the error code;
  - returned strings are Julia `String`s;
  - times are `Int64` nanoseconds (`cosim_to_nanoseconds(seconds)`).
"""
module Libcosim

import Artifacts
import Base.Libc.Libdl

const libname = Sys.iswindows() ? "cosim_c.dll" : Sys.isapple() ? "libcosim_c.dylib" : "libcosim_c.so"

"""
The path of the C library: from the `libcosim_c` artifact for this platform
(see Artifacts.toml; Pkg downloads it when the package is installed), or
LIBCOSIM_C_LIBRARY, e.g. a build tree. Evaluated when the package is
(pre)compiled; artifact paths are content-addressed and stable.
"""
function find_library()
    override = get(ENV, "LIBCOSIM_C_LIBRARY", "")
    isempty(override) || return override
    toml = joinpath(@__DIR__, "..", "Artifacts.toml")
    hash = isfile(toml) ? Artifacts.artifact_hash("libcosim_c", toml) : nothing
    hash === nothing && error("Libcosim: no libcosim binaries for this platform " *
                              "(no `libcosim_c` artifact for it in $toml)")
    dir = Artifacts.artifact_path(hash)
    isdir(dir) || error("Libcosim: the libcosim binaries are not installed ($dir); " *
                        "run `import Pkg; Pkg.instantiate()`")
    return joinpath(dir, "lib", libname)
end

const libcosim_c = find_library()

"""A libcosim error, with its cosim::errc code."""
struct CosimError <: Exception
    code::Int
    message::String
end
Base.showerror(io::IO, e::CosimError) = print(io, "CosimError(", e.code, "): ", e.message)

"""An object owned by Julia; released with its C `*_delete` function when collected."""
mutable struct Handle
    ptr::Ptr{Cvoid}
    deleter::Symbol
end
Base.unsafe_convert(::Type{Ptr{Cvoid}}, h::Handle) = h.ptr

const deleters = Dict{Symbol,Ptr{Cvoid}}()

function own(ptr::Ptr{Cvoid}, deleter::Symbol)
    ptr == C_NULL && return nothing
    h = Handle(ptr, deleter)
    finalizer(h) do x
        f = get!(deleters, x.deleter) do
            Libdl.dlsym(Libdl.dlopen(libcosim_c), x.deleter)
        end
        ccall(f, Cvoid, (Ptr{Cvoid},), x.ptr)
    end
    return h
end

function take_string(ptr::Ptr{Cchar}, free::Bool)
    ptr == C_NULL && return ""
    s = unsafe_string(ptr)
    free && ccall((:cosim_free_string, libcosim_c), Cvoid, (Ptr{Cchar},), ptr)
    return s
end

function check_error()
    code = ccall((:cosim_last_error_code, libcosim_c), Cint, ())
    code == 0 && return
    msg = take_string(ccall((:cosim_last_error_message, libcosim_c), Ptr{Cchar}, ()), true)
    ccall((:cosim_clear_last_error, libcosim_c), Cvoid, ())
    throw(CosimError(code, msg))
end

include("generated.jl")

function __init__()
    if Sys.iswindows()
        # Windows does not search a DLL's own directory for the DLLs it
        # depends on; load the bundled ones first (in any order that works).
        dir = dirname(libcosim_c)
        pending = filter(f -> endswith(lowercase(f), ".dll") && f != libname, readdir(dir))
        while !isempty(pending)
            loaded = filter(f -> Libdl.dlopen(joinpath(dir, f); throw_error=false) !== nothing, pending)
            isempty(loaded) && break
            setdiff!(pending, loaded)
        end
    end
    Libdl.dlopen(libcosim_c)
end

end # module
